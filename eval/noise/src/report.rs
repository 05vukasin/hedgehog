//! Markdown report: robustness curves, invariant failure rates, crashes and example seeds.
//! Everything below the `HAND-WRITTEN` marker of an existing report is kept.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;

use crate::check::INVARIANTS;
use crate::families::{self, FAMILIES};
use crate::Outcome;

pub const MARKER: &str = "<!-- HAND-WRITTEN: everything below this line is kept when the report is regenerated -->";

fn pct(a: usize, b: usize) -> String {
    if b == 0 { "–".into() } else { format!("{:.0}", 100.0 * a as f64 / b as f64) }
}

pub fn render(rs: &[Outcome], ts: &[f64], seeds: u64, secs: f64, real: &[String], out: &Path) -> String {
    let mut s = String::new();
    let fams: Vec<usize> = {
        let mut v: Vec<usize> = rs.iter().map(|o| o.family).collect();
        v.dedup();
        v
    };
    let crashes: Vec<&Outcome> = rs.iter().filter(|o| o.paths.iter().any(|p| p.is_err())).collect();
    let n_runs = rs.len() * 2;
    let ms: f64 = rs.iter().map(|o| o.ms[0] + o.ms[1]).sum::<f64>() / n_runs.max(1) as f64;
    writeln!(s, "# Noise robustness report").unwrap();
    writeln!(s).unwrap();
    writeln!(
        s,
        "Generated by `eval/noise` (`noise_eval`): {} families × {} intensities × {seeds} seeds = {} scenarios, each normalized \
         with `--rules-only` and with the learned model ({n_runs} runs, {secs:.0} s, {ms:.1} ms per normalize). \
         Real clean tables mixed into the bases: {}.",
        fams.len(),
        ts.len(),
        rs.len(),
        if real.is_empty() { "none (no $HEDGEHOG_DATA)".to_string() } else { real.join(", ") }
    )
    .unwrap();
    writeln!(s).unwrap();
    if crashes.is_empty() {
        writeln!(s, "**Crashes / panics: 0.**").unwrap();
    } else {
        writeln!(s, "## ⚠ Crashes / panics: {}", crashes.len()).unwrap();
        writeln!(s).unwrap();
        for o in crashes.iter().take(20) {
            for (p, r) in o.paths.iter().enumerate() {
                if let Err(e) = r {
                    writeln!(s, "- `--repro {} {:.2} {}` ({}): {e}", FAMILIES[o.family], ts[o.ti], o.seed, ["rules", "model"][p]).unwrap();
                }
            }
        }
    }
    writeln!(s).unwrap();
    writeln!(s, "## How to run").unwrap();
    writeln!(s).unwrap();
    writeln!(s, "```sh").unwrap();
    writeln!(s, "export CARGO_TARGET_DIR=$PWD/target-noise HEDGEHOG_DATA=/path/to/testdata").unwrap();
    writeln!(s, "eval/noise/sweep.sh {seeds}        # capped jobs of one family x 5 intensities x <= 40 seeds (<= 200 workbooks each), then this report").unwrap();
    writeln!(s, "$CARGO_TARGET_DIR/release/noise_eval --repro subtotals 0.75 3   # one scenario: the sheet, both paths, every invariant").unwrap();
    writeln!(s, "```").unwrap();
    writeln!(s).unwrap();
    writeln!(
        s,
        "A scenario **passes** when every applicable invariant holds for every cell it covers. Intensity 0 is the clean \
         table (title, header, body); 1 is the hardest variant of the family. Generated sheets go to `--work` (failing \
         examples are copied to `<work>/failures/`), never into the repository."
    )
    .unwrap();
    writeln!(s).unwrap();
    writeln!(s, "Invariants:").unwrap();
    writeln!(s).unwrap();
    for (k, d) in INVARIANTS {
        writeln!(s, "- `{k}`: {d}").unwrap();
    }
    writeln!(s, "- crash: normalize (or the reader) panicked; counted as a failure of every invariant.").unwrap();
    writeln!(s).unwrap();

    // curves
    writeln!(s, "## Robustness curves (scenario pass rate %, rules / model)").unwrap();
    writeln!(s).unwrap();
    write!(s, "| family |").unwrap();
    for t in ts {
        write!(s, " t={t} |").unwrap();
    }
    writeln!(s, " drop 0→1 (model) |").unwrap();
    write!(s, "|---|").unwrap();
    for _ in ts {
        write!(s, "---|").unwrap();
    }
    writeln!(s, "---|").unwrap();
    let mut tot = vec![[0usize; 3]; ts.len()];
    for &f in &fams {
        write!(s, "| `{}` |", FAMILIES[f]).unwrap();
        let mut model = Vec::new();
        for (ti, _) in ts.iter().enumerate() {
            let c: Vec<&Outcome> = rs.iter().filter(|o| o.family == f && o.ti == ti).collect();
            let r = c.iter().filter(|o| o.pass(0)).count();
            let m = c.iter().filter(|o| o.pass(1)).count();
            tot[ti][0] += r;
            tot[ti][1] += m;
            tot[ti][2] += c.len();
            model.push(if c.is_empty() { 0.0 } else { m as f64 / c.len() as f64 });
            write!(s, " {} / {} |", pct(r, c.len()), pct(m, c.len())).unwrap();
        }
        let drop = (model.first().unwrap_or(&0.0) - model.last().unwrap_or(&0.0)) * 100.0;
        let d = if drop >= 40.0 { format!("**{drop:.0}**") } else { format!("{drop:.0}") };
        writeln!(s, " {d} |").unwrap();
    }
    write!(s, "| **all** |").unwrap();
    for x in &tot {
        write!(s, " {} / {} |", pct(x[0], x[2]), pct(x[1], x[2])).unwrap();
    }
    writeln!(s, " |").unwrap();
    writeln!(s).unwrap();

    // invariant failure rates
    for (p, name) in [(1usize, "model"), (0, "rules only")] {
        writeln!(s, "## Failing scenarios per invariant, {name} (% of scenarios where it applies, t > 0)").unwrap();
        writeln!(s).unwrap();
        write!(s, "| family |").unwrap();
        for (k, _) in INVARIANTS {
            write!(s, " {k} |").unwrap();
        }
        writeln!(s).unwrap();
        write!(s, "|---|").unwrap();
        for _ in INVARIANTS {
            write!(s, "---|").unwrap();
        }
        writeln!(s).unwrap();
        for &f in &fams {
            write!(s, "| `{}` |", FAMILIES[f]).unwrap();
            for (k, _) in INVARIANTS {
                let mut app = 0;
                let mut fail = 0;
                for o in rs.iter().filter(|o| o.family == f && ts[o.ti] > 0.0) {
                    match &o.paths[p] {
                        Ok(m) => {
                            if let Some(i) = m.get(k).filter(|i| i.applicable) {
                                app += 1;
                                if !i.pass() {
                                    fail += 1;
                                }
                            }
                        }
                        Err(_) => {
                            app += 1;
                            fail += 1;
                        }
                    }
                }
                let cell = if app == 0 {
                    "".to_string()
                } else if fail * 4 >= app {
                    format!("**{}**", pct(fail, app))
                } else {
                    pct(fail, app)
                };
                write!(s, " {cell} |").unwrap();
            }
            writeln!(s).unwrap();
        }
        writeln!(s).unwrap();
    }

    // examples
    writeln!(s, "## Failure examples (first failing seed per family and invariant, model path; rules where only rules fail)").unwrap();
    writeln!(s).unwrap();
    for &f in &fams {
        let mut lines: BTreeMap<&str, String> = BTreeMap::new();
        for p in [1usize, 0] {
            for o in rs.iter().filter(|o| o.family == f) {
                let Ok(m) = &o.paths[p] else { continue };
                for (k, inv) in m {
                    if inv.pass() || lines.contains_key(k) {
                        continue;
                    }
                    lines.insert(
                        k,
                        format!(
                            "  - `{k}` ({}): `--repro {} {:.2} {}` — {} — *{}*",
                            ["rules", "model"][p],
                            FAMILIES[f],
                            ts[o.ti],
                            o.seed,
                            inv.first.clone().unwrap_or_default().replace('|', "/"),
                            o.desc.replace('|', "/")
                        ),
                    );
                }
            }
        }
        writeln!(s, "- **{}** — {}", FAMILIES[f], families::describe(FAMILIES[f])).unwrap();
        if lines.is_empty() {
            writeln!(s, "  - no failures").unwrap();
        }
        let order: Vec<&str> = INVARIANTS.iter().map(|x| x.0).collect();
        let mut ks: Vec<&&str> = lines.keys().collect();
        ks.sort_by_key(|k| order.iter().position(|x| x == *k));
        for k in ks {
            writeln!(s, "{}", lines[*k]).unwrap();
        }
    }
    writeln!(s).unwrap();
    // keep the hand-written part
    let kept = std::fs::read_to_string(out).ok().and_then(|old| old.split_once(MARKER).map(|(_, b)| b.to_string()));
    writeln!(s, "{MARKER}").unwrap();
    if let Some(k) = kept {
        s.push_str(k.trim_start_matches('\n'));
    }
    s
}
